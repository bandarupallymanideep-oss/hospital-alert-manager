function generateTrend(baseHR: number, baseSpO2: number, baseTemp: number, baseSBP: number, baseDBP: number, baseRR: number) {
  const points = [];
  const hours = ['24h ago', '20h ago', '16h ago', '12h ago', '8h ago', '4h ago', '2h ago', '1h ago', '30m ago', 'Just now'];
  for (let i = 0; i < hours.length; i++) {
    const factor = (i === hours.length - 1) ? 0 : (Math.random() - 0.5) * 4;
    points.push({
      time: hours[i],
      heartRate: Math.round(baseHR + factor * 1.5),
      spo2: Math.min(100, Math.round(baseSpO2 + factor * 0.5)),
      temperature: Number((baseTemp + (Math.random() - 0.5) * 0.3).toFixed(1)),
      systolicBP: Math.round(baseSBP + factor * 2),
      diastolicBP: Math.round(baseDBP + factor * 1.2),
      respiratoryRate: Math.round(baseRR + factor * 0.8)
    });
  }
  return points;
}

